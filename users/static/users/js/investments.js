document.addEventListener("DOMContentLoaded", function () {

    console.log("investments.js loaded");


    // =====================================================
    // ASSET ALLOCATION CHART
    // =====================================================

    const allocationCanvas =
        document.getElementById("allocationChart");

    const holdingsElement =
        document.getElementById("holdings-data");


    console.log(
        "Allocation canvas:",
        allocationCanvas
    );

    console.log(
        "Holdings element:",
        holdingsElement
    );

    console.log(
        "Chart.js:",
        typeof Chart
    );


    if (
        allocationCanvas &&
        holdingsElement &&
        typeof Chart !== "undefined"
    ) {

        try {

            // Get JSON generated by Django json_script
            const holdings = JSON.parse(
                holdingsElement.textContent
            );


            console.log(
                "Holdings:",
                holdings
            );


            const labels =
                Object.keys(holdings);


            const values =
                Object.values(holdings)
                    .map(Number);


            console.log(
                "Labels:",
                labels
            );


            console.log(
                "Values:",
                values
            );


            // Check that there is something
            // to display in the pie chart.

            const hasValues =
                values.some(
                    value =>
                        Number.isFinite(value) &&
                        value > 0
                );


            if (!hasValues) {

                console.warn(
                    "Asset allocation contains no positive values."
                );

                return;
            }


            // Create chart

            new Chart(
                allocationCanvas.getContext("2d"),
                {
                    type: "pie",

                    data: {

                        labels: labels,

                        datasets: [
                            {

                                data: values,

                                backgroundColor: [
                                    "#f2a900",
                                    "#3c3c3d",
                                    "#26a17b"
                                ],

                                borderColor: "#ffffff",

                                borderWidth: 2
                            }
                        ]
                    },


                    options: {

                        responsive: true,

                        maintainAspectRatio: false,

                        plugins: {

                            legend: {

                                display: true,

                                position: "bottom"
                            }

                        }
                    }
                }
            );


            console.log(
                "Asset allocation chart rendered successfully."
            );


        } catch (error) {

            console.error(
                "Asset allocation chart error:",
                error
            );

        }

    } else {

        console.error(
            "Could not initialize asset allocation chart."
        );

    }



    // =====================================================
    // PROFIT & LOSS HISTORY CHART
    // =====================================================

    const historyCanvas =
        document.getElementById("historyChart");


    if (
        historyCanvas &&
        typeof Chart !== "undefined"
    ) {

        try {

            new Chart(
                historyCanvas.getContext("2d"),
                {

                    type: "line",

                    data: {

                        labels: [
                            "Jan",
                            "Feb",
                            "Mar",
                            "Apr",
                            "May"
                        ],

                        datasets: [
                            {

                                label: "Profit/Loss",

                                data: [
                                    200,
                                    300,
                                    150,
                                    400,
                                    350
                                ],

                                borderWidth: 2,

                                fill: false,

                                tension: 0.3
                            }
                        ]
                    },


                    options: {

                        responsive: true,

                        maintainAspectRatio: false,

                        plugins: {

                            legend: {

                                display: true,

                                position: "top"
                            }

                        }
                    }
                }
            );


            console.log(
                "History chart rendered successfully."
            );


        } catch (error) {

            console.error(
                "History chart error:",
                error
            );

        }

    }

});